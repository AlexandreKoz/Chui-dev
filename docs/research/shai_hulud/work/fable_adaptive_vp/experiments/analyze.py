"""Turn the result files into results/SUMMARY.md and results/gate_evaluation.json.

Equal-cost comparison.  The N-body ladder of each PM grid defines error-vs-
cost curves (cost = wall time, peak resident memory above the post-warm-up
baseline, or bytes of persistent state).  For every sheet arm the N-body
error "at equal cost" is read off the ladder by log-log interpolation
(flagged when it had to be extrapolated beyond the ladder).  Gate B:
  equal wall time:  sheet error <= N-body error       (position AND density)
  equal memory:     sheet error <= 0.5 N-body error   (position AND density)
at t = 3, >= 30 % folded labels, PM >= 256^2, on two consecutive PM grids.

Usage: python3 analyze.py
"""
from __future__ import annotations

import json
import math
import os

import common

R = common.RESULTS
METRICS = ("x_rms", "rho_rel_l2", "force_rel_l2", "p_rms")


def load(name):
    p = os.path.join(R, name)
    return json.load(open(p)) if os.path.exists(p) else None


def state_mb(r):
    m = r["memory"]
    if "particles" in m:
        return m["state_floats"] * 8 / 2 ** 20
    return (m["state_floats"] + m["carrier_coefficient_floats"]) * 8 / 2 ** 20


def interp(ladder, cost, key, snap):
    """log-log interpolation of the ladder error at `cost`.  ladder: list of
    (cost, run) sorted by cost.  Returns (value, extrapolated?)."""
    xs = [math.log(c) for c, _ in ladder]
    ys = [math.log(r["snaps"][snap][key]) for _, r in ladder]
    x = math.log(cost)
    if x <= xs[0]:
        i, ex = 0, x < xs[0] - 1e-9
    elif x >= xs[-1]:
        i, ex = len(xs) - 2, x > xs[-1] + 1e-9
    else:
        i = max(j for j in range(len(xs) - 1) if xs[j] <= x)
        ex = False
    t = (x - xs[i]) / (xs[i + 1] - xs[i])
    return math.exp(ys[i] + t * (ys[i + 1] - ys[i])), ex


def fmt(v, p=2):
    return "—" if v is None else (f"{v:.{p}e}" if (abs(v) < 1e-2 or abs(v) >= 1e4) and v != 0 else f"{v:.3g}")


def gate_table(d, ng, snap="300"):
    runs = {k: v for k, v in d["runs"].items() if not v.get("failed") and "#r" not in k}
    nb = {k: v for k, v in runs.items() if v["spec"]["kind"] == "nbody"}
    costs = dict(wall=lambda r: r["wall_s"], rss=lambda r: max(r["peak_rss_incr_mb"], 0.5), state=state_mb)
    ladders = {c: sorted(((f(r), r) for r in nb.values()), key=lambda t: t[0]) for c, f in costs.items()}
    rows = []
    for name, r in runs.items():
        if r["spec"]["kind"] != "sheet":
            continue
        s = r["snaps"][snap]
        row = dict(arm=name, wall_s=r["wall_s"], rss_mb=r["peak_rss_incr_mb"], state_mb=state_mb(r), nodes=r["nodes_final"],
                   folded=s["folded_fraction"], x_rms=s["x_rms"], rho=s["rho_rel_l2"], force=s["force_rel_l2"])
        for c, f in costs.items():
            for key, short in (("x_rms", "x"), ("rho_rel_l2", "rho"), ("force_rel_l2", "F")):
                v, ex = interp(ladders[c], f(r), key, snap)
                row[f"nb_{short}_eq_{c}"] = v
                row[f"ratio_{short}_eq_{c}"] = s[key] / v
                row[f"extrap_{c}"] = ex
        row["pass_wall"] = bool(row["ratio_x_eq_wall"] <= 1.0 and row["ratio_rho_eq_wall"] <= 1.0)
        row["pass_wall_position_only"] = bool(row["ratio_x_eq_wall"] <= 1.0)
        row["pass_mem_rss"] = bool(row["ratio_x_eq_rss"] <= 0.5 and row["ratio_rho_eq_rss"] <= 0.5)
        row["pass_mem_state"] = bool(row["ratio_x_eq_state"] <= 0.5 and row["ratio_rho_eq_state"] <= 0.5)
        row["folded_ok"] = bool(s["ref_folded_fraction"] >= 0.30)
        rows.append(row)
    return rows


def main():
    out = ["# SHAI-HULUD adaptive VP — measured results (generated by `experiments/analyze.py`)\n",
           "All numbers are read from `results/*.json`.  Units: box 1, total mass 1, 4πG = 1, t on a static background.",
           "`x_rms`, `p_rms`: RMS error against the 4096² grid-matched particle control; for sheets it is the error of the",
           "**carrier evaluated on a uniform 256² label lattice** (not only at nodes); for N-body it is the error at the particles",
           "that share labels with the control lattice.  `rho`: ‖ρ−ρ_ref‖₂/‖ρ_ref−1‖₂ on the PM grid.  `F`: relative L2 error of the",
           "PM acceleration field.  `RSS+`: peak resident memory above the baseline measured after imports and JIT warm-up.",
           "`state`: bytes of persistent evolving state (N-body: x, p; sheet: nodal d, p, Σ, key + carrier coefficients).\n"]
    ge = {}
    # ---------------------------------------------------------------- baseline
    b = load("exp00_baseline_repro.json")
    if b:
        out += ["## 0. Baseline reproduction (original code, this environment)\n",
                f"* 512² control at PM 64²: bit-identical to the saved snapshot: **{b['control_bit_identical']}**",
                f"* arms {', '.join(b['arms'])}: largest relative deviation of (x_rms, p_rms, rho, E) from the saved JSON: **{b['max_relative_deviation_arms']:.1e}**",
                f"* frozen conventions: `{json.dumps(b['frozen'])}`\n"]
    # ---------------------------------------------------------------- field convergence
    fc = load("exp02_field_convergence.json")
    if fc:
        out += ["## 1. Field convergence and quality of the controls\n", "| quantity | t=1.5 | t=2.0 | t=2.5 | t=3.0 |", "|:--|--:|--:|--:|--:|"]
        for k, v in fc["field_convergence"].items():
            out.append(f"| position change PM {k} (x_rms, 2048² particles) | " + " | ".join(fmt(v[s]["x_rms"]) for s in ("150", "200", "250", "300")) + " |")
        for k, v in fc["self_convergence"].items():
            out.append(f"| control 2048² vs 4096² at PM {k}: x_rms | " + " | ".join(fmt(v[s]["x_rms"]) for s in ("150", "200", "250", "300")) + " |")
            out.append(f"| control 2048² vs 4096² at PM {k}: rho | " + " | ".join(fmt(v[s]["rho_rel_l2"]) for s in ("150", "200", "250", "300")) + " |")
        for k, v in fc["folded"].items():
            out.append(f"| folded label fraction (det Dx<0), PM {k} | " + " | ".join(f"{v[s]:.3f}" for s in ("150", "200", "250", "300")) + " |")
        out.append("")
    # ---------------------------------------------------------------- gate
    for ng in (256, 512):
        d = load(f"exp03_gate_ng{ng}.json")
        if not d:
            continue
        runs = {k: v for k, v in d["runs"].items() if not v.get("failed")}
        failed = [k for k, v in d["runs"].items() if v.get("failed")]
        out += [f"## 2.{1 if ng == 256 else 2} Gate benchmark, PM {ng}² (clean sequential timings; control 4096²)\n",
                f"meta: numpy {d['meta']['numpy']}, scipy {d['meta']['scipy']}, numba {d['meta']['numba']}, source `{d['meta']['source_sha256_16']}`, "
                f"{d['meta']['cpu_count']} cores, 1 thread per arm, arms run one at a time.\n",
                "| arm | nodes(t=3) | samples/step | wall s | CPU s | RSS+ MB | state MB | x_rms t=2 | x_rms t=3 | p_rms t=3 | rho t=3 | F t=3 | P(k) max err (k≤N/4) | folded | first split t |",
                "|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"]
        for name, r in runs.items():
            if "#r" in name:
                continue
            s3, s2 = r["snaps"]["300"], r["snaps"]["200"]
            fs = (r.get("controller") or {}).get("first_split_t")
            if r.get("manual_refinements"):
                fs = r["manual_refinements"][0]["t"]
            out.append(f"| {name} | {r['nodes_final']} | {r['deposit_samples_per_step']:.0f} | {r['wall_s']:.1f} | {r['cpu_s']:.1f} | {r['peak_rss_incr_mb']:.1f} | "
                       f"{state_mb(r):.1f} | {fmt(s2['x_rms'])} | {fmt(s3['x_rms'])} | {fmt(s3['p_rms'])} | {fmt(s3['rho_rel_l2'])} | {fmt(s3['force_rel_l2'])} | "
                       f"{fmt(s3['pk_rel_max_to_quarter_nyq'])} | {s3['folded_fraction']:.3f} | {'—' if fs is None else f'{fs:.2f}'} |")
        if failed:
            out.append(f"\nFAILED arms (recorded, not tuned away): {failed}")
        # timing variance
        rep = {}
        for name, r in runs.items():
            base = name.split("#r")[0]
            rep.setdefault(base, []).append(r["wall_s"])
        var = {k: v for k, v in rep.items() if len(v) > 1}
        if var:
            out += ["", "Timing repeatability (wall s of repeated arms): " + "; ".join(f"{k}: {', '.join(f'{w:.1f}' for w in v)}" for k, v in var.items()), ""]
        # conservation / structure
        out += ["", "Conservation and structure at t = 3 (sheet integrals by leaf quadrature of the carrier):", "",
                "| arm | mass ledger−1 | grid mass−1 | Px | Py | (E−E0)/K | loop-action max dev | interface jumps [F], [∂F], [∂²F], [∂³F], [∂⁴F] (÷scale) |", "|:--|--:|--:|--:|--:|--:|--:|:--|"]
        for name, r in runs.items():
            if "#r" in name:
                continue
            s3 = r["snaps"]["300"]
            led = s3.get("ledger_mass")
            j = s3.get("interface_jumps")
            js = "—" if not j or not j.get("n") else ", ".join(f"{a / max(b, 1e-300):.0e}" for a, b in zip(j["jump"][:5], j["scale"][:5]))
            out.append(f"| {name} | {'—' if led is None else f'{led - 1:.0e}'} | {s3['mass'] - 1:.0e} | {s3['Px']:.1e} | {s3['Py']:.1e} | "
                       f"{(s3['E'] - r['E0']) / s3['K']:.1e} | {fmt(s3.get('loop_action_max_dev'))} | {js} |")
